"""Сколько раз отложенный период уже просматривался.

Запечатанный отложенный период тем и ценен, что его смотрят один раз. Каждый
следующий просмотр — это выбор, сделанный по нему, пусть и косвенный: увидев
результат, автор меняет код, и следующая цифра уже несёт в себе память о
предыдущей. Журнал показывает, что 2026H1 просматривался многократно и на
разных состояниях кода, тогда как докстринг final_eval.py утверждал обратное.

Отдельного запечатанного среза взять неоткуда: данные заканчиваются 30 июня
2026. Поэтому единственный честный выход — назвать число просмотров вслух и
считать результат валидационным, а не отложенным.
"""
import collections
import json
import sys

from mkl.config import PATHS

sys.stdout.reconfigure(encoding="utf-8")


def uses() -> list[dict]:
    path = PATHS.experiments / "log.jsonl"
    if not path.exists():
        return []
    recs = [json.loads(l) for l in path.open(encoding="utf-8")]
    fin = [r for r in recs if r.get("step") == "FINAL"]
    by = collections.defaultdict(lambda: {"heads": set(), "n": 0})
    for r in fin:
        key = (str(r.get("ts", ""))[:16], str(r.get("git_sha", ""))[:8])
        by[key]["heads"].add(r.get("head"))
        by[key]["n"] += 1
    return [{"ts": k[0], "git_sha": k[1], "heads": sorted(v["heads"]), "n": v["n"]}
            for k, v in sorted(by.items())]


def report() -> str:
    u = uses()
    shas = {x["git_sha"] for x in u}
    lines = [
        "# Просмотры отложенного периода",
        "",
        f"Отложенный период 2026-01-01 … 2026-06-30 просматривался "
        f"**{len(u)} раз** на **{len(shas)} состояниях кода**.",
        "",
        "Запечатанный период тем и ценен, что его смотрят один раз. Каждый "
        "следующий просмотр — это выбор, сделанный по нему: увидев результат, "
        "автор меняет код, и следующая цифра несёт память о предыдущей. "
        "Другого отложенного среза взять неоткуда — данные заканчиваются "
        "30 июня 2026.",
        "",
        "**Как это читать.** Приведённые в отчётах числа следует считать "
        "валидационными, а не полученными на запечатанном периоде. Они не "
        "подогнаны намеренно, но и не защищены от подгонки протоколом.",
        "",
        "| когда | состояние кода | голов |",
        "|---|---|---|",
    ]
    lines += [f"| {x['ts']} | `{x['git_sha']}` | {x['n']} |" for x in u]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    dst = PATHS.reports / "holdout_uses.md"
    dst.write_text(report(), encoding="utf-8")
    print(report())
